    #[test]
    fn staged_config_submission_chunks_and_references() {
        // A >4KiB opaque config envelope → 2 chunks + 1 SubmitStagedConfig.
        let envelope = vec![0x5Au8; 4500];
        let messages = build_staged_config_submission(99, &envelope).unwrap();
        assert_eq!(messages.len(), 3);
        let h = hash(&envelope);
        match messages.last().unwrap() {
            KernelInboxMessage::SubmitStagedConfig(reff) => {
                assert_eq!(reff.staging_id, 99);
                assert_eq!(reff.payload_hash, h);
            }
            other => panic!("expected SubmitStagedConfig, got {:?}", other),
        }
        // All messages round-trip.
        for m in &messages {
            let b = encode_kernel_inbox_message(m).unwrap();
            let d = decode_kernel_inbox_message(&b).unwrap();
            assert_eq!(encode_kernel_inbox_message(&d).unwrap(), b);
        }
    }
