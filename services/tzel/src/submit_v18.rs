    #[test]
    fn binding_is_self_consistent_with_verifier_walk() {
        // The producer's derived (tree_roots, out_hash) must equal what the
        // kernel's verify_snark_tree re-derives from the same binding —
        // i.e. the binding's slots fold to tree_roots[0] and the OutHash
        // equation holds. We check the derivation directly here (the full
        // Groth16 check needs a real proof over these publics).
        let ops = vec![shield_op(7), transfer_op(8)];
        let preimages: Vec<&[F]> =
            ops.iter().map(|o| o.output_preimage.as_slice()).collect();
        let derived = build_tree_binding(&preimages).unwrap();

        // Re-run the kernel-side walk over the SAME slots and confirm the
        // root preprocessed-root equals tree_roots[0].
        let walk_slots: Vec<MvLeafSlot<'_>> = derived
            .binding
            .leaf_slots
            .iter()
            .map(|slot| match slot {
                KernelLeafSlot::DeclaredOp(i) => MvLeafSlot::Declared {
                    output_preimage: preimages[*i as usize],
                },
                KernelLeafSlot::Opaque { root, outputs } => MvLeafSlot::Opaque(MvNodePublics {
                    preprocessed_root_lanes: *root,
                    output_lanes: *outputs,
                }),
            })
            .collect();
        let internal = pinned_internal_root_lanes(derived.binding.depth).unwrap();
        let root = derive_mv_root_publics(LEAF_CIRCUIT_ROOT_LANES, &internal, &walk_slots).unwrap();
        assert_eq!(
            root_lanes_to_bytes(&root.preprocessed_root_lanes),
            derived.tree_roots[0]
        );
        let expected_out =
            tzel_verifier::snark::compute_expected_out_hash_mv(&derived.tree_roots[0], &root.output_lanes);
        assert_eq!(expected_out, derived.out_hash);
    }

    #[test]
    fn chunk_payload_splits_and_shares_hash() {
        let payload = vec![0xABu8; MAX_STAGE_CHUNK_BYTES * 2 + 17];
        let chunks = chunk_payload(42, &payload).unwrap();
        assert_eq!(chunks.len(), 3);
        let h = hash(&payload);
        for (i, c) in chunks.iter().enumerate() {
            assert_eq!(c.staging_id, 42);
            assert_eq!(c.chunk_index, i as u16);
            assert_eq!(c.chunk_count, 3);
            assert_eq!(c.payload_hash, h);
            assert!(c.bytes.len() <= MAX_STAGE_CHUNK_BYTES);
        }
        // Reassembly equals the original.
        let mut reassembled = Vec::new();
        for c in &chunks {
            reassembled.extend_from_slice(&c.bytes);
        }
        assert_eq!(reassembled, payload);
    }

